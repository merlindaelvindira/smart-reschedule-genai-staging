"""# **Learning Curve Graph**"""

def plot_learning_curve(estimator, X, y, title=None):

    # Set dynamic title based on the estimator's actual class name if not provided
    if title is None:
        title = f"Learning Curve ({estimator.__class__.__name__} - Intent Classification)"

    # Calculate training and validation scores using 5-Fold Cross Validation
    train_sizes, train_scores, test_scores = learning_curve(
        estimator, X, y,
        cv=5,
        n_jobs=-1,
        train_sizes=np.linspace(0.1, 1.0, 5), # 5 distinct points (10% to 100%)
        scoring='f1_macro'
    )

    # Calculate mean and standard deviation for training and test scores
    train_scores_mean = np.mean(train_scores, axis=1)
    train_scores_std = np.std(train_scores, axis=1)
    test_scores_mean = np.mean(test_scores, axis=1)
    test_scores_std = np.std(test_scores, axis=1)

    # Plot Configuration
    plt.figure(figsize=(10, 6))
    plt.title(title, fontsize=14, fontweight='bold')
    plt.xlabel("Number of Training Samples", fontsize=12)
    plt.ylabel("F1-Score (Macro) - Higher is Better", fontsize=12)
    plt.grid(True, linestyle='--', alpha=0.7)

    # Restrict y-axis slightly above 1.0 for better visual scaling
    plt.ylim(0.0, 1.05)

    # Plot Standard Deviation shaded areas
    plt.fill_between(train_sizes, train_scores_mean - train_scores_std,
                     train_scores_mean + train_scores_std, alpha=0.1, color="blue")
    plt.fill_between(train_sizes, test_scores_mean - test_scores_std,
                     test_scores_mean + test_scores_std, alpha=0.1, color="orange")

    # Plot Mean Lines
    plt.plot(train_sizes, train_scores_mean, 'o-', color="blue",
             label="Training Score")
    plt.plot(train_sizes, test_scores_mean, 's-', color="orange",
             label="Cross-Validation (Test) Score")

    plt.legend(loc="lower right", fontsize=10)
    plt.tight_layout()
    plt.show()


    # Get the final scores at the maximum training size (100% of data)
    final_train_score = train_scores_mean[-1]
    final_test_score = test_scores_mean[-1]
    score_gap = final_train_score - final_test_score

    print("\n📈 LEARNING CURVE DIAGNOSTIC ANALYSIS:")
    print("-" * 50)
    print(f"Final Training Score     : {final_train_score:.4f}")
    print(f"Final Cross-Val Score    : {final_test_score:.4f}")
    print(f"Score Gap (Difference)   : {score_gap:.4f}")
    print("-" * 50)

    print("\n💡 CONCLUSION & RECOMMENDATION:")

    # Logic for diagnosis based on common ML thresholds
    # Threshold values (0.75 for baseline, 0.10 for gap) can be adjusted if needed
    if final_train_score < 0.75 and final_test_score < 0.75:
        print("⚠️ HIGH BIAS (UNDERFITTING) DETECTED")
        print("- The model struggles to learn the underlying patterns in the data.")
        print("- Both training and validation scores are low.")
        print("- Recommendation: Try a more complex model, use n-grams with wider ranges, or reduce regularization.")

    elif score_gap > 0.10:
        print("⚠️ HIGH VARIANCE (OVERFITTING) DETECTED")
        print("- The model memorizes the training data but fails to generalize well to unseen data.")
        print("- The gap between the training score and validation score is significant.")
        print("- Recommendation: Collect more training data, simplify the model, or increase regularization.")

    else:
        print("✅ GOOD FIT (OPTIMAL MODEL)")
        print("- The training and validation scores are converging nicely with a minimal gap.")
        print("- The model generalizes well to unseen data.")
        if final_test_score > 0.90:
            print("- Recommendation: The model is highly accurate and ready for production deployment.")
        else:
            print("- Recommendation: The model is stable. Adding more data might yield slight improvements, but it is acceptable as-is.")
    print("\n")

# Execute the function
